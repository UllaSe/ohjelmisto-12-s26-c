"use strict";

let number = 3; // number = 3
number = number * 7; // number = 3 * 7 = 21
number = 1 + number / 2; // number = 1 + 21 / 2 = 1 + 10.5 = 11.5
console.log(number);

let counter = 3;
counter++;
console.log(counter);
counter--;
console.log(counter);

let value = 3;
value *= 2; // value = value * 2
value /= 3; // value = value / 3
value += 7; // value = value + 7
value -= 8; // value = value - 8
console.log(value);

console.log(10 % 3); // 10 mod 3
